CREATE TABLE IF NOT EXISTS PROFISSIONAL_ATUA_US(
    cpf_profissional VARCHAR(11),
    cnes_unidade VARCHAR(10),
    CONSTRAINT PK_PROFISSIONAL_ATUA PRIMARY KEY(cpf_profissional, cnes_unidade),
    CONSTRAINT FK_PROFISSIONAL_ATUA_1 FOREIGN KEY(cpf_profissional)
                REFERENCES PROFISSIONAL(cpf)
                ON DELETE CASCADE,
    CONSTRAINT FK_PROFISSIONAL_ATUA_2 FOREIGN KEY(cnes_unidade)
                REFERENCES UNIDADE_SAUDE(cnes)
                ON DELETE CASCADE
);

